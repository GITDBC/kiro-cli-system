"""
Repository-root discovery and shared file helpers.

The checks run from an installed package under ``tools/driftcheck/``,
so the repository they validate can no longer be reached by counting
parent directories: the count depends on where inside the package the
caller lives and breaks silently whenever a module moves. Discovery is
therefore marker-based — the root is the nearest ancestor holding both
``.kiro/`` and ``tools/``.
"""

# Standard libraries
import re
from pathlib import Path
from typing import Final

# Directories that together identify the repository root. Either one
# alone is too common to be conclusive.
ROOT_MARKERS: Final[tuple[str, ...]] = (".kiro", "tools")

# Verbatim kiro.dev mirror, regenerated by `docsync` and listed in
# .prettierignore. Its files are not authored here, so conventions that
# apply to hand-written docs are not enforced against them.
VENDORED_SKILL: Final[str] = "kiro-cli-reference"


def is_repo_root(path: Path) -> bool:
    """
    Report whether a directory looks like the repository root.

    Args:
        path: Candidate directory.

    Returns:
        True when every root marker exists inside the directory.
    """
    return all((path / marker).is_dir() for marker in ROOT_MARKERS)


def find_repo_root(start: Path | None = None) -> Path:
    """
    Locate the repository root by walking upward from a starting point.

    Walks from ``start`` (this module's file by default) towards the
    filesystem root and returns the first directory containing every
    marker in ROOT_MARKERS. When the default starting point yields
    nothing — which happens for a non-editable install, where the
    package lives inside a virtualenv rather than in the working tree —
    the search is retried from the current working directory.

    Args:
        start: Path to walk up from. Defaults to this module's file.

    Returns:
        Absolute path to the repository root.

    Raises:
        ValueError: If no ancestor holds the marker directories.
    """
    origins: list[Path] = [(start or Path(__file__)).resolve()]
    if start is None:
        origins.append(Path.cwd().resolve())
    for origin in origins:
        for candidate in (origin, *origin.parents):
            if is_repo_root(candidate):
                return candidate
    markers = ", ".join(f"{marker}/" for marker in ROOT_MARKERS)
    searched = ", ".join(str(origin) for origin in origins)
    message = (
        f"cannot locate the repository root: no ancestor of {searched} "
        f"contains all of {markers}. Pass --root explicitly."
    )
    raise ValueError(message)


def read_text(path: Path) -> str:
    """
    Read a text file, tolerating undecodable bytes.

    Args:
        path: File to read.

    Returns:
        File contents, or an empty string when the file is missing.
    """
    if not path.is_file():
        return ""
    return path.read_text(encoding="utf-8", errors="replace")


def contains_word(text: str, word: str) -> bool:
    """
    Report whether text contains word as a whole word.

    Mirrors ``grep -w``: the match must not be adjacent to another word
    character, so hyphenated neighbours still count as a match.

    Args:
        text: Haystack to search.
        word: Literal needle.

    Returns:
        True when the word occurs as a standalone token.
    """
    pattern = rf"(?<!\w){re.escape(word)}(?!\w)"
    return re.search(pattern, text) is not None
